        commands: __DIR__.'/../routes/console.php',
        health: '/up',
    )
    ->withMiddleware(function (Middleware $middleware) {
        $middleware->alias([
            'can.manage.draw' => EnsureCanManageDraw::class,
        ]);
    })
    ->withExceptions(function ($exceptions) {
        //
    })->create();

